using YotsubaShaderCross;

// Translates a SPIR-V binary to GLSL with the C# port of SPIRV-Cross.
//   dotnet run --project samples/SpirvToGlsl -- shader.spv [version]
if (args.Length == 0)
{
    Console.Error.WriteLine("usage: SpirvToGlsl <shader.spv> [glsl version, default 450]");
    return 1;
}

// 1. SPIR-V words -> intermediate representation
byte[] bytes = File.ReadAllBytes(args[0]);
uint[] words = new uint[bytes.Length / 4];
Buffer.BlockCopy(bytes, 0, words, 0, words.Length * 4);

var parser = new Parser(new CppVector<uint>(words));
parser.parse();

// 2. Choose the backend and its options (same names and defaults as the C++ API)
var glsl = new CompilerGLSL(parser.get_parsed_ir());
CompilerGLSL.Options options = glsl.get_common_options();
options.version = args.Length > 1 ? uint.Parse(args[1]) : 450u;
options.es = false;
options.vulkan_semantics = true;
glsl.set_common_options(options);

// 3. Emit
Console.WriteLine(glsl.compile().str());
return 0;
