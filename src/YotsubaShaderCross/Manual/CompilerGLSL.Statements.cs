namespace YotsubaShaderCross;

// Hand-written translation of the variadic statement helpers of spirv_glsl.hpp
// (C++ variadic templates have no direct C# equivalent; every argument is streamed through JoinArg).
public partial class CompilerGLSL
{

    public void statement_inner(params JoinArg[] ts)
    {
        Span<JoinArg> span = ts;
        if(span.IsEmpty) return;
        foreach (var joinArg in span)
        {
            buffer.Append(joinArg.S);
            statement_count++;
        }
    }

    public void statement(params JoinArg[] ts)
    {
        if (is_forcing_recompilation())
        {
            // Do not bother emitting code while force_recompile is active.
            statement_count++;
            return;
        }

        if (redirect_statement != null)
        {
            redirect_statement.push_back(Std.join(ts));
            statement_count++;
        }
        else
        {
            for (uint i = 0; i < indent; i++)
                buffer.Append("    ");
            statement_inner(ts);
            buffer.Append('\n');
        }
    }

    public void statement_no_indent(params JoinArg[] ts)
    {
        var old_indent = indent;
        indent = 0;
        statement(ts);
        indent = old_indent;
    }
}
